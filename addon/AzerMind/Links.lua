-- Explicit entity IDs only. Never guess an item or quest from a display name.
local colors = {npc="ff8fc9df", object="ffd3b66f", item="ffd3b66f", spell="ff8fc9df", quest="ffffd36a", azermindinstance="ff8fc9df"}
local itemColors = {[0]="ff9d9d9d", [1]="ffd3b66f", [2]="ff1eff00", [3]="ff0070dd", [4]="ffa335ee", [5]="ffff8000", [6]="ffe6cc80", [7]="ff00ccff"}

-- Edit boxes can handle differently wrapped links inconsistently. Preserve the
-- full item payload but always supply a conventional eight-digit color wrapper.
function AzerMind.NormalizeItemLink(link)
	if type(link) ~= "string" then return link end
	local payload, name = link:match("|H(item:[^|]+)|h(.-)|h")
	if not payload then return link end
	local quality = tonumber(link:match("|cnIQ(%d+):"))
	local query = (C_Item and C_Item.GetItemInfo) or GetItemInfo
	if query then
		local ok, _, _, value = pcall(query, payload)
		if ok and type(value) == "number" then quality = value end
	end
	local hex = link:match("|c(%x%x%x%x%x%x%x%x)")
	hex = itemColors[quality] or hex or colors.item
	if hex:lower() == "ffffffff" then hex = colors.item end
	return "|c" .. hex .. "|H" .. payload .. "|h" .. name .. "|h|r"
end
function AzerMind.EntityLink(kind, id, name)
	id = tonumber(id)
	if not colors[kind] or not id or id < 1 or id > 2147483647 or id ~= math.floor(id) then return name end
	name = tostring(name):gsub("[|%[%]\r\n]", "")
	local payload = kind .. ":" .. id
	if kind == "quest" then payload = payload .. ":-1" end
	local link = "|c" .. colors[kind] .. "|H" .. payload .. "|h[" .. name .. "]|h|r"
	if kind == "item" then return AzerMind.NormalizeItemLink(link) end
	return link
end

function AzerMind.CollapseSources(text)
	local sources, body, collecting = {}, {}, false
	for line in (text .. "\n"):gmatch("(.-)\n") do
		local heading = line:match("^%s*#*%s*%**Sources%**:?%s*$")
		if heading then
			collecting = true
		elseif collecting and line:find("https?://") then
			sources[#sources + 1] = line
		elseif not (collecting and line:match("^%s*$")) then
			collecting = false
			body[#body + 1] = line
		end
	end
	if #sources == 0 then return text, sources end
	return table.concat(body, "\n"):gsub("%s+$", "") .. "\n\n\3", sources
end

function AzerMind.RichMessage(role, text)
	local names = {}
	if role == "user" then
		local at = tostring(text):find("--- Linked from the game ---", 1, true)
		if at then
			for name, kind, id in text:sub(at):gmatch("%[([^%]]+)%]%s+(%a+)%s+(%d+)") do
				if colors[kind] then names[name] = {kind, id} end
			end
		end
	end
	local plain = AzerMind.MessageText(role, text)
	local sources = {}
	if role == "assistant" then plain, sources = AzerMind.CollapseSources(plain) end
	plain = plain:gsub("|", "||")
	-- Convert explicit references generated by the agent; everything else is plain text.
	local links = {}
	local function Keep(kind, id, name)
		links[#links + 1] = AzerMind.EntityLink(kind, id, name)
		return "\1" .. #links .. "\2"
	end
	plain = plain:gsub("%[%[(%a+):(%d+):([^%]]+)%]%]", Keep)
	if role == "user" then
		plain = plain:gsub("%[([^%]]+)%]", function(name)
			local entity = names[name]
			if entity then return Keep(entity[1], entity[2], name) end
			return "[" .. name .. "]"
		end)
	end
	plain = plain:gsub("\1(%d+)\2", function(index) return links[tonumber(index)] or "" end)
	return plain:gsub("\3", ("|cff8fc9df|Hazermindsources:1|hSources (" .. #sources .. ")|h|r")), sources
end

function AzerMind.CopyMessage(role, text)
	return (AzerMind.MessageText(role, text):gsub("%[%[%a+:%d+:([^%]]+)%]%]", "[%1]"))
end

-- Presentation only. Transport, saved history and copy keep the full snapshot.
function AzerMind.PresentMessage(role, text)
	if role~="user" or type(text)~="string" then return text end
	local visible,items,blocks=text,{},{}
	local first="--- Selected inventory items ---"
	local last="--- End selected inventory items ---"
	while true do
		local start=visible:find(first,1,true)
		local finish=start and visible:find(last,start+#first,true)
		if not finish then break end
		local block=visible:sub(start,finish+#last-1)
		local found={}
		for line in block:gmatch("[^\n]+") do
			local plain=AzerMind.PlainText(line)
			local location,name,tail=plain:match("^([^:]+):%s*%[([^%]]+)%](.*)$")
			if location and ({Equipped=true,Bags=true,Bank=true,Catalog=true})[location] then
				local count=tail:match("×%s*(%d+)") or tail:match("[xX]%s*(%d+)") or "1"
				found[#found+1]={name=name,count=count,location=location,id=tonumber(line:match("|Hitem:(%d+)"))}
			end
		end
		if #found==0 then break end
		for _,item in ipairs(found) do items[#items+1]=item end
		blocks[#blocks+1]=block
		visible=visible:sub(1,start-1)..visible:sub(finish+#last)
	end
	if #items==0 then return text end
	local item=items[1]
	local label=item.name.." ×"..item.count.." · "..item.location
	if #items>1 then label=label.."  +"..(#items-1).." items" end
	return visible:gsub("^%s+",""):gsub("%s+$",""),{label=label,count=#items,id=item.id,full=table.concat(blocks,"\n\n")}
end

function AzerMind.OpenAcceptedQuest(id)
	id = tonumber(id)
	if not id then return false end
	local index
	if C_QuestLog and C_QuestLog.GetLogIndexForQuestID then
		local ok, value = pcall(C_QuestLog.GetLogIndexForQuestID, id)
		if ok then index = value end
	elseif GetQuestLogIndexByID then
		local ok, value = pcall(GetQuestLogIndexByID, id)
		if ok then index = value end
	end
	if type(index) ~= "number" or index < 1 then return false end
	if not QuestMapFrame_OpenToQuestDetails and C_AddOns and C_AddOns.LoadAddOn then pcall(C_AddOns.LoadAddOn, "Blizzard_WorldMap") end
	if QuestMapFrame_OpenToQuestDetails then
		local ok = pcall(QuestMapFrame_OpenToQuestDetails, id)
		if ok then return true end
	end
	if QuestLogFrame and SelectQuestLogEntry and ShowUIPanel then
		local ok = pcall(function() SelectQuestLogEntry(index); ShowUIPanel(QuestLogFrame) end)
		if ok then return true end
	end
	return false
end

function AzerMind.SetupLinks(frame)
	if not frame.SetHyperlinksEnabled then return end
	frame:SetHyperlinksEnabled(true)
	local function Valid(link)
		if type(link) == "string" then return link:match("^(%a+):(%d+)") end
	end
	frame:SetScript("OnHyperlinkEnter", function(self, link)
		local kind, id = Valid(link)
		if kind == "azermindsources" and self.sources then
			GameTooltip:SetOwner(self, "ANCHOR_CURSOR")
			GameTooltip:ClearLines(); GameTooltip:AddLine("Sources", 0.91, 0.87, 0.78)
			for _, source in ipairs(self.sources) do GameTooltip:AddLine(source, 0.8, 0.85, 0.87, true) end
			GameTooltip:AddLine("Click to copy references", 0.6, 0.65, 0.65)
			GameTooltip:Show(); return
		end
		if not colors[kind] then return end
		if kind == "azermindinstance" then
			GameTooltip:SetOwner(self,"ANCHOR_CURSOR"); GameTooltip:ClearLines()
			local r=AzerMind.InstanceByID(id); GameTooltip:AddLine(r and r.name or "Unknown instance"); GameTooltip:AddLine("Click for bosses, loot and location",0.7,0.7,0.7); GameTooltip:Show(); return
		end
		GameTooltip:SetOwner(self, "ANCHOR_CURSOR")
		GameTooltip:ClearLines()
		local ok = pcall(GameTooltip.SetHyperlink, GameTooltip, link)
		if not ok or (GameTooltip.NumLines and GameTooltip:NumLines() == 0) then
			GameTooltip:ClearLines(); GameTooltip:AddLine("Details unavailable in this client"); GameTooltip:AddLine(link, 0.7, 0.7, 0.7)
		end
		GameTooltip:Show()
	end)
	frame:SetScript("OnHyperlinkLeave", function() GameTooltip:Hide() end)
	frame:SetScript("OnHyperlinkClick", function(self, link, text, button)
		local kind, id = Valid(link)
		if kind == "azermindsources" and self.sources then AzerMind.ShowCopy(table.concat(self.sources, "\n")); return end
		if not colors[kind] then return end
		if kind=="npc" or kind=="object" then AzerMind.ShowSourceBrowser(kind,tonumber(id)); return end
        if kind == "azermindinstance" then
			local r=AzerMind.InstanceByID(id)
			if r then
				if IsShiftKeyDown and IsShiftKeyDown() then local c=AzerMind.SettingsState(); if c then AzerMind.AppendQuestDraft(AzerMind.InstanceLink(r),c.id) end
    else AzerMind.ShowInstanceDetails(r) end
			end
			return
		end
		if button == "RightButton" then AzerMind.ShowEntityMenu(kind, tonumber(id), link, text)
		elseif IsShiftKeyDown and IsShiftKeyDown() and ChatEdit_InsertLink then ChatEdit_InsertLink(text)
		elseif kind == "quest" and (not button or button == "LeftButton") and AzerMind.OpenAcceptedQuest(id) then GameTooltip:Hide()
		elseif SetItemRef then pcall(SetItemRef, link, text, button or "LeftButton") end
	end)
end

local entityMenu
function AzerMind.ShowEntityMenu(kind, id, payload, text)
	if not colors[kind] or not id then return end
	local chat = AzerMind.SettingsState()
	if not chat then return end
	GameTooltip:Hide()
	local T = AzerMindTheme
	if not entityMenu then
		entityMenu = CreateFrame("Frame", "AzerMindEntityMenu", UIParent)
		entityMenu:SetWidth(246); entityMenu:SetFrameStrata("TOOLTIP"); entityMenu:SetFrameLevel(200)
		entityMenu:SetClampedToScreen(true); entityMenu:EnableMouse(true)
		T.Surface(entityMenu, "window")
		entityMenu.title = T.Label(entityMenu, "", 12, -12, T.fonts.heading)
		entityMenu.title:SetWidth(222); entityMenu.title:SetWordWrap(false); entityMenu.title:SetJustifyH("LEFT")
		entityMenu.rows = {}
		table.insert(UISpecialFrames, "AzerMindEntityMenu")
		entityMenu:RegisterEvent("GLOBAL_MOUSE_DOWN")
		entityMenu:SetScript("OnEvent", function(self)
			if not self:IsShown() then return end
			local x, y = GetCursorPosition()
			local scale = self:GetEffectiveScale()
			x, y = x / scale, y / scale
			local left, right, bottom, top = self:GetLeft(), self:GetRight(), self:GetBottom(), self:GetTop()
			if left and (x < left or x > right or y < bottom or y > top) then self:Hide() end
		end)
	end
	local menu = entityMenu
	local name = AzerMind.PlainText(text or (kind .. " " .. id)):gsub("[%[%]]", "")
	local link = "|c" .. colors[kind] .. "|H" .. payload .. "|h[" .. name:gsub("|", "") .. "]|h|r"
	local function Ask(question)
		AzerMind.AppendQuestDraft(question .. " " .. link, chat.id)
	end
	local actions = {}
	local function Add(label, callback) table.insert(actions, {label, callback}) end
	if kind == "item" then
		Add("Where to find (database)",function() AzerMind.ShowSourceBrowser("item",id) end)
        Add("Ask AI where to find it", function() Ask("Where can I get this item in WoW Forever? Check drops, quest rewards, vendors and crafting as applicable:") end)
		Add("What is it used for?", function() Ask("What is this item used for in WoW Forever? Check whether I should keep it for a quest, crafting or another purpose:") end)
		Add("Compare with my equipment", function()
			local current = AzerMind.SettingsState()
			if current and current.id == chat.id then AzerMind.AttachEquipment(); Ask("Compare this item with the relevant slot in my attached equipped items:") end
		end)
	elseif kind == "quest" then
        Add("NPCs and sources (database)",function() AzerMind.ShowSourceBrowser("quest",id) end)
		Add("Mark objective on map", function() AzerMind.MarkQuestOnMap(id,false) end)
		Add("Mark turn-in on map", function() AzerMind.MarkQuestOnMap(id,true) end)
		Add("Remove map mark", function() if AzerMindMap then AzerMindMap.RemoveQuestMark(id) end end)
		Add("Show in quest log", function()
			if not AzerMind.OpenAcceptedQuest(id) then AzerMind.ShowCopy("This quest is not in your log, or the client could not open it.\nhttps://www.wowhead.com/forever/quest=" .. id) end
		end)
		Add("How do I complete it?", function() Ask("How do I complete this quest in WoW Forever? Use my current progress when available:") end)
		Add("Where do I turn it in?", function() Ask("Who do I turn this quest in to, and where are they in WoW Forever?") end)
		Add("Check prerequisites", function() Ask("What are the requirements and prerequisite quests for this WoW Forever quest? Do not assume it is unlocked:") end)
	elseif kind == "spell" then
		Add("How do I learn it?", function() Ask("How do I learn this spell in WoW Forever, including level and trainer or quest requirements?") end)
		Add("Explain this spell", function() Ask("Explain how this spell works in WoW Forever and when it is useful for my character:") end)
	end
	Add("Link to draft", function() AzerMind.AppendQuestDraft(link, chat.id) end)
	Add("Copy name", function() AzerMind.ShowCopy(name) end)
	Add("Wowhead URL", function() AzerMind.ShowCopy("https://www.wowhead.com/forever/" .. kind .. "=" .. id) end)
	menu.title:SetText(name)
	for i, action in ipairs(actions) do
		local row = menu.rows[i]
		if not row then
			row = T.Button(menu, "", 230, 25, function() end, "LEFT")
			row:SetPoint("TOPLEFT", menu, "TOPLEFT", 8, -36 - (i-1)*28)
			menu.rows[i] = row
		end
		local callback = action[2]
		row:SetText(action[1]); row:SetScript("OnClick", function() menu:Hide(); callback() end); row:Show()
	end
	for i = #actions+1, #menu.rows do menu.rows[i]:Hide() end
	menu:SetHeight(44 + #actions*28)
	local x, y = GetCursorPosition()
	local scale = UIParent:GetEffectiveScale()
	menu:ClearAllPoints(); menu:SetPoint("TOPLEFT", UIParent, "BOTTOMLEFT", x/scale, y/scale)
	menu:Show()
end
